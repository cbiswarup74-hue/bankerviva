import { NextResponse } from 'next/server';
import nodemailer from 'nodemailer';

export async function POST(req: Request) {
  try {
    const { fullName, email, inquiryType, examTrack, message } = await req.json();

    // Dynamically route: General/Institutional -> info@, Candidate/Tech -> care@
    const targetRecipient =
      inquiryType?.includes('Institutional') || inquiryType?.includes('Feedback')
        ? 'info@bankerviva.com'
        : 'care@bankerviva.com';

    // Configure Zoho SMTP transporter
    const transporter = nodemailer.createTransport({
      host: 'smtp.zoho.in',
      port: 465,
      secure: true, // true for port 465
      auth: {
        user: process.env.ZOHO_MAIL_USER,
        pass: process.env.ZOHO_APP_PASSWORD,
      },
    });

    // Send the notification email
    await transporter.sendMail({
      from: `"BankerViva Desk" <${process.env.ZOHO_MAIL_USER}>`,
      to: targetRecipient,
      replyTo: email, // Clicking "Reply" in Zoho Mail replies directly to the candidate
      subject: `[${inquiryType || 'General Inquiry'}] ${examTrack || 'Portal'} - ${fullName || 'Candidate'}`,
      html: `
        <div style="font-family: Arial, sans-serif; line-height: 1.6; color: #1e293b; max-width: 600px; padding: 16px; border: 1px solid #e2e8f0; border-radius: 8px;">
          <h2 style="color: #2563eb; margin-top: 0;">New Portal Inquiry Received</h2>
          
          <table style="width: 100%; border-collapse: collapse; margin-bottom: 20px; font-size: 14px;">
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; font-weight: bold; width: 140px; color: #64748b;">Candidate Name:</td>
              <td style="padding: 8px 0; color: #0f172a;">${fullName || 'N/A'}</td>
            </tr>
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; font-weight: bold; color: #64748b;">Candidate Email:</td>
              <td style="padding: 8px 0; color: #2563eb;"><strong>${email}</strong></td>
            </tr>
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; font-weight: bold; color: #64748b;">Inquiry Category:</td>
              <td style="padding: 8px 0; color: #0f172a;">${inquiryType || 'General'}</td>
            </tr>
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; font-weight: bold; color: #64748b;">Exam Track:</td>
              <td style="padding: 8px 0; color: #0f172a;">${examTrack || 'N/A'}</td>
            </tr>
          </table>

          <div style="background: #f8fafc; border-left: 4px solid #3b82f6; padding: 12px 16px; border-radius: 4px; font-size: 14px;">
            <strong style="color: #334155;">Candidate Message / Requirement:</strong>
            <p style="margin: 8px 0 0 0; color: #1e293b; white-space: pre-wrap;">${message || 'No additional details provided.'}</p>
          </div>

          <p style="font-size: 11px; color: #94a3b8; margin-top: 24px; text-align: center;">
            This email was automatically generated by BankerViva Portal Contact Desk.
          </p>
        </div>
      `,
    });

    return NextResponse.json({ success: true }, { status: 200 });
  } catch (error: any) {
    console.error('SMTP Transmission Error:', error?.message || error);
    return NextResponse.json({ error: error?.message || 'Failed to transmit inquiry' }, { status: 500 });
  }
}